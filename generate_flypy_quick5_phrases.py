#!/usr/bin/env python3
"""Generate flypy_quick5_phrases.dict.yaml from luna_pinyin phrases."""

from __future__ import annotations

import os
import sys
from itertools import product

from essay_lib import Pair, load_pairs
from generate_flypy_quick5 import (
    CANGJIE5,
    LUNA_PINYIN,
    _cangjie_quicks,
    is_cjk,
    parse_dict,
    pinyin_to_flypy,
)

OUTPUT = "flypy_quick5_phrases.dict.yaml"
LEGACY = "flypy_quick5_phrases_legacy.tsv"


def parse_phrases(path: str) -> list[tuple[str, list[str]]]:
    phrases: list[tuple[str, list[str]]] = []
    in_header = True
    in_phrase_section = False
    with open(path, encoding="utf-8") as f:
        for line in f:
            stripped = line.strip()
            if not stripped:
                continue
            if stripped.startswith("#"):
                if stripped == "#以下爲詞組":
                    in_phrase_section = True
                continue
            if in_header:
                if stripped == "...":
                    in_header = False
                continue
            if not in_phrase_section:
                continue
            parts = stripped.split("\t")
            if len(parts) < 2:
                continue
            phrase = parts[0]
            syllables = parts[1].split()
            if len(syllables) != len(phrase):
                continue
            if not all(is_cjk(char) for char in phrase):
                continue
            phrases.append((phrase, syllables))
    return phrases


def _codes_for(
    phrase: str,
    syllables: list[str],
    cangjie: dict[str, list[tuple[str, str]]],
) -> list[str]:
    dp_lists: list[list[str]] = []
    for syllable in syllables:
        codes = sorted(pinyin_to_flypy(syllable))
        if not codes:
            return []
        dp_lists.append(codes)

    cj_lists: list[list[str]] = []
    for char in phrase:
        quicks = sorted(_cangjie_quicks(cangjie.get(char, [])))
        if not quicks:
            return []
        cj_lists.append(quicks)

    return [
        " ".join(f"{dp}/{cj}" for dp, cj in zip(dps, cjs))
        for dps in product(*dp_lists)
        for cjs in product(*cj_lists)
    ]


def phrase_codes(
    phrase: str,
    syllables: list[str],
    cangjie: dict[str, list[tuple[str, str]]],
    pairs: list[Pair],
) -> list[tuple[str, str]]:
    mapping: dict[str, str] = {}
    for pair in pairs:
        if pair.scope == "char" and pair.type == "ortho":
            mapping[pair.preferred] = pair.variant
            mapping[pair.variant] = pair.preferred

    variants = {phrase}
    for index, char in enumerate(phrase):
        if char in mapping:
            variants.add(phrase[:index] + mapping[char] + phrase[index + 1 :])

    result: list[tuple[str, str]] = []
    for variant in sorted(variants):
        for code in _codes_for(variant, syllables, cangjie):
            result.append((variant, code))
    return result


def main() -> int:
    print(f"Parsing {CANGJIE5} ...")
    cangjie = parse_dict(CANGJIE5)
    print(f"Parsing phrases from {LUNA_PINYIN} ...")
    phrases = parse_phrases(LUNA_PINYIN)
    try:
        pairs = load_pairs("essay_pairs.tsv")
    except FileNotFoundError:
        pairs = []

    rows: list[tuple[str, str]] = []
    seen: set[tuple[str, str]] = set()

    if os.path.exists(LEGACY):
        with open(LEGACY, encoding="utf-8") as f:
            for line in f:
                line = line.rstrip("\n")
                if not line or line.startswith("#"):
                    continue
                parts = line.split("\t")
                if len(parts) < 2:
                    continue
                key = (parts[0], parts[1])
                if key not in seen:
                    seen.add(key)
                    rows.append(key)

    for phrase, syllables in phrases:
        for text, code in phrase_codes(phrase, syllables, cangjie, pairs):
            key = (text, code)
            if key in seen:
                continue
            seen.add(key)
            rows.append(key)
    rows.sort(key=lambda row: (row[0], row[1]))

    header = f"""# Rime dictionary
# encoding: utf-8
#
# flypy_quick5_phrases - 小鶴雙拼＋倉頡速成輔助碼詞組
#
# Generated by generate_flypy_quick5_phrases.py
# Source: {LUNA_PINYIN}, {CANGJIE5}, essay_pairs.tsv
#

---
name: flypy_quick5_phrases
version: "0.1"
sort: by_weight
use_preset_vocabulary: true
...

"""
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
        for text, code in rows:
            f.write(f"{text}\t{code}\n")

    print(f"Generated {len(rows)} entries -> {OUTPUT}")
    print(f"Total unique phrases: {len({row[0] for row in rows})}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
