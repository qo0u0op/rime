#!/usr/bin/env python3
"""Regenerate a Taiwan-first rime essay from the upstream frequency list."""

from __future__ import annotations

import argparse
import os
import sys

from essay_lib import (
    apply_pairs,
    derive_phrase_pairs,
    load_essay,
    load_pairs,
    write_essay,
)

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

CORE = "爲裏着衆麪喫牀峯羣為裡著眾麵吃床峰群"


def build_report(args, input_count, output_count, report, final):
    from collections import Counter

    actions = Counter(r["action"] for r in report)
    overshoot = [r for r in report if r["action"] == "overshoot"]
    skipped = [r for r in report if r["action"] == "skip"]
    conflicts = [r for r in report if r["action"] == "conflict"]
    zero_core = [c for c in CORE if final.get(c, 0.0) == 0.0]
    lines = [
        f"essay: {args.essay}",
        f"pairs: {args.pairs}",
        f"input entries: {input_count}",
        f"output entries: {output_count}",
        f"added entries: {output_count - input_count}",
        f"pairs applied: {actions.get('ok', 0)}",
        f"char variants banded: {actions.get('banded', 0)}",
        f"phrase variants zeroed: {actions.get('zeroed', 0)}",
        f"overshoot: {len(overshoot)}",
        f"conflicts: {len(conflicts)}",
        f"skipped: {len(skipped)}",
        "",
        "--- overshoot (final gap) ---",
    ]
    for r in overshoot:
        lines.append(
            f"{r['preferred']} -> {r['variant']}\t"
            f"weight={r.get('weight')} target={r.get('target')} gap={r.get('gap')}"
        )
    lines += ["", "--- conflicts (skipped, same key on both sides) ---"]
    for r in conflicts:
        lines.append(f"{r['preferred']} -> {r['variant']}")
    lines += ["", "--- skipped (neither side in upstream) ---"]
    for r in skipped:
        lines.append(f"{r['preferred']} -> {r['variant']}")
    lines += ["", "--- core characters still at weight 0 ---"]
    lines.append(" ".join(zero_core) if zero_core else "(none)")
    lines += [
        "",
        "note: .gram is not regenerated by this pipeline; rebuild it separately if needed.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--essay", default="/usr/share/rime-data/essay.txt")
    parser.add_argument("--pairs", default=os.path.join(HERE, "essay_pairs.tsv"))
    parser.add_argument("--out", default=os.path.join(ROOT, "essay.txt"))
    parser.add_argument("--report", default=os.path.join(HERE, "essay_report.txt"))
    parser.add_argument("--page-size", type=int, default=5)
    parser.add_argument("--gap-pages", type=int, default=3)
    parser.add_argument("--phrase-gap-pages", type=int, default=20)
    parser.add_argument("--abcn", default=os.path.join(HERE, "abcn.tsv"))
    parser.add_argument("--variant-cap", type=float, default=0.9)
    parser.add_argument("--rare-cap", type=float, default=0.1)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    essay = load_essay(args.essay)
    if not os.path.exists(args.pairs):
        print(
            f"warning: pairs file not found: {args.pairs} "
            "(essay will not be aligned)",
            file=sys.stderr,
        )
        pairs = []
    else:
        pairs = load_pairs(args.pairs)
        if not pairs:
            print(
                f"warning: pairs file is empty: {args.pairs}",
                file=sys.stderr,
            )
    common_chars: set[str] = set()
    rare_chars: set[str] = set()
    if os.path.exists(args.abcn):
        with open(args.abcn, encoding="utf-8") as f:
            for line in f:
                if not line or line.startswith("#"):
                    continue
                parts = line.rstrip("\n").split("\t")
                if len(parts) >= 2 and parts[1] in ("A", "B", "N"):
                    common_chars.add(parts[0])
                if len(parts) >= 2 and parts[1] == "C":
                    rare_chars.add(parts[0])
    else:
        print(
            f"warning: ABCN table not found: {args.abcn} "
            "(rare variants will not be demoted)",
            file=sys.stderr,
        )

    for char in essay:
        if len(char) != 1:
            continue
        code = ord(char)
        if (
            0x3400 <= code <= 0x4DBF
            or 0x20000 <= code <= 0x2A6DF
            or 0x2A700 <= code <= 0x2B73F
            or 0x2B740 <= code <= 0x2B81F
            or 0x2B820 <= code <= 0x2CEAF
            or 0x2CEB0 <= code <= 0x2EBEF
            or 0x30000 <= code <= 0x3134F
            or 0x31350 <= code <= 0x323AF
        ):
            rare_chars.add(char)

    derived = derive_phrase_pairs(essay, pairs)
    existing = {(p.preferred, p.variant) for p in pairs}
    pairs = pairs + [
        p for p in derived if (p.preferred, p.variant) not in existing
    ]
    out, report = apply_pairs(
        essay,
        pairs,
        page_size=args.page_size,
        gap_pages=args.gap_pages,
        phrase_gap_pages=args.phrase_gap_pages,
        common_chars=common_chars,
        rare_chars=rare_chars,
        variant_cap=args.variant_cap,
        rare_cap=args.rare_cap,
    )
    text = build_report(args, len(essay), len(out), report, out)

    if args.dry_run:
        print(text)
        return 0

    write_essay(args.out, out)
    with open(args.report, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(
        f"wrote {args.out} ({len(essay)} -> {len(out)} entries), "
        f"{len(pairs)} pairs"
    )
    print("請重新部署 Rime（重新啟動 fcitx5，或使用選單的「部署」）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
